-- PostgreSQL: review-reports.sql 적용 후, 새 애플리케이션 배포 전에 실행합니다.
BEGIN;
CREATE TABLE IF NOT EXISTS review_report_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    display_order integer NOT NULL CHECK (display_order >= 0),
    active boolean NOT NULL,
    CONSTRAINT uk_review_report_types_name UNIQUE (name)
);

ALTER TABLE review_reports ADD COLUMN IF NOT EXISTS report_type_id bigint;

-- 선택 사유 없이 저장된 신고만 보정합니다. 신규 선택 목록에는 노출하지 않습니다.
INSERT INTO review_report_types (name, display_order, active)
SELECT '기존 신고(사유 미분류)', 0, false
WHERE EXISTS (SELECT 1 FROM review_reports WHERE report_type_id IS NULL)
ON CONFLICT (name) DO UPDATE SET active = false;

UPDATE review_reports
SET report_type_id = (SELECT id FROM review_report_types WHERE name = '기존 신고(사유 미분류)')
WHERE report_type_id IS NULL;

ALTER TABLE review_reports ALTER COLUMN report_type_id SET NOT NULL;
ALTER TABLE review_reports DROP CONSTRAINT IF EXISTS fk_review_reports_type;
ALTER TABLE review_reports ADD CONSTRAINT fk_review_reports_type
    FOREIGN KEY (report_type_id) REFERENCES review_report_types(id);
CREATE INDEX IF NOT EXISTS idx_review_reports_type ON review_reports (report_type_id);
COMMIT;
