-- PostgreSQL: 애플리케이션 배포 전에 적용합니다. 기존 리뷰·회원 데이터는 유지합니다.
BEGIN;
CREATE TABLE IF NOT EXISTS review_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id bigint NOT NULL REFERENCES reviews(id),
    reporter_id bigint REFERENCES members(id),
    reason varchar(1000) NOT NULL,
    report_date date NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT uk_review_reports_daily UNIQUE (review_id, reporter_id, report_date)
);
CREATE INDEX IF NOT EXISTS idx_review_reports_created ON review_reports (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_review_reports_review_created ON review_reports (review_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_review_reports_reporter ON review_reports (reporter_id);
COMMIT;
