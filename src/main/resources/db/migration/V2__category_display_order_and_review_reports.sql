CREATE TABLE public.review_report_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    display_order integer NOT NULL CHECK (display_order >= 0),
    active boolean NOT NULL,
    CONSTRAINT uk_review_report_types_name UNIQUE (name)
);

CREATE TABLE public.review_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id bigint NOT NULL REFERENCES public.reviews(id),
    reporter_id bigint REFERENCES public.members(id),
    report_type_id bigint NOT NULL,
    reason varchar(1000) NOT NULL,
    report_date date NOT NULL,
    created_at timestamp with time zone NOT NULL,
    confirmed boolean NOT NULL DEFAULT false,
    CONSTRAINT fk_review_reports_type FOREIGN KEY (report_type_id) REFERENCES public.review_report_types(id),
    CONSTRAINT uk_review_reports_daily UNIQUE (review_id, reporter_id, report_date)
);

CREATE INDEX idx_review_reports_created ON public.review_reports (created_at DESC, id DESC);
CREATE INDEX idx_review_reports_review_created ON public.review_reports (review_id, created_at DESC, id DESC);
CREATE INDEX idx_review_reports_reporter ON public.review_reports (reporter_id);
CREATE INDEX idx_review_reports_type ON public.review_reports (report_type_id);
